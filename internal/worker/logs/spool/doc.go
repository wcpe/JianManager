// Package spool 实现 FR-510：VictoriaLogs 不可用时的**有界环形磁盘缓冲**。
//
// # 定位（必读的边界）
//
//   - 它只把「VL 重启几分钟」从丢日志变成不丢；VL 挂很久、缓冲写满之后仍然丢最旧，
//     与官方 vlagent 的 `-remoteWrite.maxDiskUsagePerURL` 语义一致。
//   - 本包**只管**文件格式的读、写、掉电恢复与容量淘汰，不接 WAL / pipeline / 投递路径
//     （那是 P1.3 的事）、不持有水位账本、不决定投递成功与否。
//
// # 三条硬约束（违反其一即不可接受）
//
//  1. **不 fsync**。生产数据盘是机械盘（sda，ROTA=1），2026-10-30 裁定不做 fsync 落盘，
//     写入只依赖 OS 页缓存。本包任何路径都不调 Sync/Fdatasync，也不做任何刷盘动作。
//  2. **只 append，绝不回退覆盖写**。机械盘顺序写实测 274MB/s、随机写差一个量级，
//     所以本包**没有第二个写入点**：全程只有一个随追加前进的写位，没有索引块、
//     没有读指针回写、没有圈首标记。唯一的覆写是恢复后从截断位置继续往前写——
//     那之后面的字节本来就是垃圾。
//  3. **一条坏记录不能阻塞后面所有记录**：遇到第一条校验失败的记录即视为尾部边界，
//     不报错、不清空文件、不挂死、不给上游背压——已读出的完整条目全部可用，缓冲能继续写。
//     「不阻塞」= 不挂死、不崩溃、不拒绝服务，**不是**「跳过坏记录继续往后读」：
//     跳过会把环回拼接点的残骸当数据，所以宁可不做。
//
// # 文件布局
//
// 单文件，`[64B 文件头][capacity 字节数据区]`。文件头只在创建文件时写一次，此后**从不改写**
// （回写头部就是随机写，而且掉电时会把整个文件的元信息一并打坏）。
//
// 数据区是字节环，里面只有两种帧，都是「24B 定长头 + 变长体」、全小端：
//
//	记录帧  magic=JMSP  length=payload 长度  crc=payload 的 CRC32C  seq=单调序号  reserved=0
//	填充帧  magic=JAPD  length=死区字节数     其余字段为 0
//
// 序号从 1 开始，0 永远非法——这条硬规矩直接拦住「只写了一半的记录头」（magic 与 length
// 落了盘而 seq 还是零），否则它会被当成一条 seq=0 的空记录收下。
//
// **记录绝不跳数据区尾部**：在圈尾放不下时，先在圈尾写一道填充帧（告知读者/恢复者
// 「从这到文件尾全是死区」），再回绕到偏移 0 继续写。这条不变量使「任意一条记录都能独立
// 解析」成立，是恢复能只靠一次顺序读就把文件读解出来的前提。
//
// # 环形语义
//
// 用两个单调序号描述读写位：`readSeq`（最旧可读）与 `writeSeq`（下一个待分配）。
// `[readSeq, writeSeq)` 就是可读区间，两者相等即空。物理读写位是 `readOff` / `writeOff`。
// 可读区在环序上**永远连续**（可能夹一道填充帧），`used` 就是这段的环距离。
// 写满时**推进读位丢弃最旧**，不给上游背压（2026-10-29 裁定：暂停会让整源停采 20+ 小时）。
//
// # 掉电恢复（核心）
//
// 因为不 fsync，文件尾部可能是半条记录。恢复从数据区偏移 0 顺序扇，逐条校验：
// 魔数 → 长度是否荒谬 → 保留位 → payload CRC → **序号严格递增且连续**。遇到第一条
// 不满足的就停，把它当作**尾部边界**；已读出的条目全部可用，后续写入从该边界继续往前写。
//
// 三个细节都不是冗余的：
//
//   - **序号递增**：环跑满一圈后新记录从偏移 0 覆盖已被丢弃的旧字节，写前沿后面留下的是
//     上一圈的残骸——它们**依旧是 CRC 合法的记录**，只能靠序号识破。
//   - **序号连续（seq = prev+1）**：不仅增加一道残骸防关，也保证了写入顺序与物理顺序一致，
//     恢复只需一次前向扇描就能定位完整的运行段。
//   - **终止性**：若碰上一道填充帧，恢复**停下而不跳转**（否则会从偏移 0 重新开始、无限绕圈）。
//
// # 恢复只能从偏移 0 开始扇，为什么会不丢数据
//
// 写入严格按物理顺序前进，所以同一圈内写入过的物理区间永远是 [0, 写前沿) 的一段连续前缀。
// 因此从 0 扇到第一道断点，拿到的正好是「这一圈写过的全部」：
//
//   - 未环回：拿到 [0, writeOff)，**包括已经 Ack 过的旧条目**（它们还在磁盘上）。
//   - 已环回：拿到新一圈 [0, writeOff)；断点处是上一圈的残骸（seq 更小）或填充帧，于是停下。
//
// 代价是**重启后会重投已 Ack 过的条目（至多一整圈）**。见下面的「已知代价」。
//
// # 已知代价（如实记录，不粉饰）
//
//   - **确认位不落盘、重启会重投**。readSeq 只在内存里，重启后整个磁盘上的段落会被重读一遍
//     （包括已经 Ack 的）。这是「绝不 in-place 写」的直接代价：要记住读位就得回写文件。
//     依靠 event_id（hash(log_source_id, source_generation, record_start, record_end,
//     parser_version)）在 VL 侧去重；与 FR-505「重启后至多重读一段并重复投递」的既有口径一致。
//     若 P1.3 要消除重投，应另加 FR-506 那种「整表重写 + rename」的游标旁路文件，
//     而不是在本文件里改指针。
//   - **环回后崩机会丢掉旧的那一段**。环写满一圈后，可读区会跨过物理末端拆成两段；恢复只能
//     从 0 找回新那段，旧那段（当时最旧、本就在淘汰前沿上的）的起点无处可存。所以恰好处于
//     「已环回且未落定」时掉电，旧那段会丢。它只发生在缓冲已写满**一整圈**之后（持续故障）；
//     而那时系统既定语义本来就是「丢最旧」。这是为了守住「绝不回写」而故意的取舍，不是遗漏。
//     而目标场景（VL 重启几分钟）根本不会写满一圈，因此不受影响。
//   - **同圈内一条坏记录之后的数据会丢**：按「停在原地」处理，下一次写入就从那里开始覆盖。
//     环中段的损坏不是健康文件系统的预期事件，而跳过它继续读有把残骸当数据的风险。
//   - 恢复成本 O(有效字节) 而非 O(容量)：扫到边界就停，不扫空着的容量。
//     100MiB 满环在 274MB/s 顺序读下约 0.4s，只在启动时发生一次。
//
// # 并发
//
// 所有方法由一把 mutex 串行化，多 goroutine 并发 Append/Peek/Ack 是安全的；
// 但写入本身就是磁盘顺序路径，并发写不会更快（它只保证不会写坏）。
