// Package retention 实现日志保留策略：按级别/来源设定保留期，并把策略翻译成
// 可执行的删除计划。
//
// # 边界：什么在这里做，什么不在这里做
//
// 本包只负责**策略**与**执行**两块，不重复造已有的清理机制：
//
//   - 索引侧（SQLite）的清理**已有实现且默认开启**：`ledger.PruneDeliveryBatches`
//     按 `Positions.Reclaim` 水位裁剪投递批次表，判据是「水位之下即恒等元」，
//     配置键 `log_index.batch_prune.*`。保留策略不该另起一套按 TTL 的索引删除——
//     索引里的表除投递批次外都是稳态有界的，水位裁剪已经足够，而且水位判据是
//     **语义安全**的（裁掉的条目对后续计算是恒等元），TTL 判据不是。
//   - 分区迁移/冷热分层已有地基：`catalog` + `lifecycle`（HOT→COLD→Rehydrate→CLEANED）。
//     本包只提供「按年龄与磁盘水位决定何时迁移」的策略输入。
//   - 本包**不碰实例本地 gz 归档**：冷层是中心侧（HOT/COLD/Rehydrate 三段路径），
//     实例本地的 gz 只是回拉来源，其清理属实例侧职责，不在本包范围内。
//
// # 为什么删除过滤器由本包生成而不是从配置读
//
// VL 的删除接口接受 LogsQL 过滤器。若把配置里的字符串直接当过滤器用，
// 一次配置误写（例如 `filter: "*"`）就能在几分钟内删掉全部日志，且删除不可逆。
// 因此本包只接受**结构化的策略**（级别 + 来源标识），过滤器由级别白名单与
// 严格的源标识字符集拼出（见 buildFilter）。配置里没有任何位置能塞进自由过滤器。
//
// # 为什么默认不执行
//
// 策略默认「计算并暴露、不落地删除」（见 Policy.Enabled 与 Sweep.VLSweep 的分工）：
// 保留期配错、或删除接口被误开，后果是**不可逆的数据丢失**，与采样折叠（有汇总事件
// 承接区间，可查可证）不是同一量级的风险。因此生效路径分两道闸：策略闸（决定
// 「保留多久」）与执行闸（决定「真的删」），后者默认关闭，且 VL 侧还需运维在
// 受管 VL 进程上加 `-delete.enable`（默认关）。
