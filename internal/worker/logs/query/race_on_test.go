package query

// raceEnabled 在 -race 构建下为 true。
//
// 用途：只在不带竞态检测时对**绝对耗时**下断言。竞态检测器给每次内存访问加检查，
// 实测把排序路径整体放慢约 5 倍（SortEvents n=2万 逆序：普通构建 100–157 ms，
// -race 构建 515 ms）。而 500 ms 阈值的存在意义是「拦回插入排序（O(n²)，实测约 4 s）」，
// 那是一个数量级之差；-race 下 515 ms 的读数既证明不了「接近 O(n log n)」也证明不了
// 「退化成 O(n²)」——它只证明了竞态检测器在拖慢一切。故该断言按本开关收窄。
//
// 与 stateindex 同名开关的口径一致（那里是 SQLite 写入路径放慢 3–5 倍，
// 绝对阈值 50 ms 同属失去意义）。**只豁免绝对耗时断言，不豁免次序/稳定性断言**——
// 后者在两种构建下都成立且必须成立。
const raceEnabled = true
