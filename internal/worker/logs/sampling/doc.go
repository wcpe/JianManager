// Package sampling 实现采集侧的日志采样、抑制与风暴降级策略。
//
// # 为什么不变量 R 是一等公民
//
// 采集侧的每一次「抑制」都必须保持**区间守恒**（invariant R）：对任何一个日志源，
// 把本批次被消费的行按位置升序排列，其 Record 区间在 rangesTouch 口径下是一条连续覆盖；
// 抑制不得在这条覆盖上留下空洞。
//
// 为什么这是硬约束（而不是可选的整洁性要求）：
// deliver 面登记的缺口判据是「缺口必须完全落在**某一段**连续覆盖区间内」
// （ledger.CoveredByPositionRanges，复审 P1-1 明确否掉了凸包判定），而连续覆盖区间由
// gapRangesOfEvents 从**实际投递的事件**的 Record 区间折出。若抑制让事件凭空消失，
// 被抑制行的位置就落进了空洞：任何跨越该位置的既有缺口（例如一次 DELIVER_ERROR 登记的
// [1000,5000)）将**永远无法自动消解**，而 ResumeAcquire 要求「零未解决缺口」
// ⇒ 该源被永久焊死在暂停态、不再产生新数据——正是 2026-10-01/02 那次
// 「13 小时零新数据」事故的形态。
//
// 因此本包的抑制**不丢弃**，而是把被抑制的行替换为**汇总事件**：
//
//   - 汇总事件的 Record 区间 = 被抑制行的精确并集跨度（仅在区间相邻时合并，
//     绝不跨越任意未被抑制的事件，故不是 min..max 凸包，也不收缩）；
//   - 汇总事件走完整管线（WAL → 投递 → 逐字段校验 → 发布），与普通事件无差别；
//   - 被抑制条数、规则、级别、首条样例全文都写进汇总事件正文与字段，
//     使「丢了多少、丢了什么」在查询面上可见，而不是静默消失。
//
// # 界定：本包不洗白「从未落库」
//
// 汇总事件只承接**本次被本包抑制的**那些行。它绝不把别的缺口原因
// （APPEND_REJECTED：append 被拒、该批从未进 WAL；PAUSED：容量门禁暂停）
// 覆盖的区间一并宣称「已落库」——那些原因不在缺口的自动消解允许名单里
// （见 ingest.gapAutoResolvableReasons），汇总事件也不会把它们带进允许名单。
//
// # 确定性
//
// 抑制决策只依赖事件自身携带的数据（级别、流、正文、EventTimeUTC），**不读挂钟**。
// 同一条 WAL 条目在重放/重投时必然得到同一结论与同一汇总事件（EventID 与
// CanonicalHash 逐字节一致），因此账本的 (EventID, CanonicalHash) 去重语义不受影响：
// 重投是「多写一次」而不是「写出一份不同的东西」。
